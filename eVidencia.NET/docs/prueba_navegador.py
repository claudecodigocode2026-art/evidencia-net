# Prueba de la demo en un navegador real (Chrome + Playwright) con los datos de ejemplo.
# Arrancar antes la aplicación con Datos__Modo=Memoria en http://localhost:5080
# Uso: python3 prueba_navegador.py [carpeta_de_capturas]
import sys, os
from playwright.sync_api import sync_playwright
B = 'http://localhost:5080'
out = (sys.argv[1] if len(sys.argv) > 1 else 'capturas').rstrip('/') + '/'
os.makedirs(out, exist_ok=True)
res = []; fallos = []; consola = []
def ok(n, c):
    res.append((n, bool(c))); print(('OK    ' if c else 'FALLO ') + n)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ.get('CHROME', '/usr/bin/google-chrome'), args=['--no-sandbox'])
    pg = b.new_page(viewport={'width': 1280, 'height': 900})
    pg.on('response', lambda r: fallos.append(f'{r.status} {r.url}') if r.status >= 400 else None)
    pg.on('pageerror', lambda e: consola.append(str(e)))
    filas = lambda: pg.locator('#grid tr.ev-row').count()
    dlg = lambda: pg.locator('.ev-dialog')
    def esperar(): pg.wait_for_timeout(500)
    pg.goto(B + '/'); pg.wait_for_selector('#grid tr.ev-row')
    ok('la raíz lleva al listado de Procesos', pg.url.endswith('/Administracion/Procesos.aspx'))
    ok('título de la página', pg.title() == 'eVidencia: Procesos')
    ok('título del listado con el número de registros', pg.inner_text('#tituloListado') == 'Procesos ( 26 )')
    ok('listado con 10 filas en la primera página', filas() == 10)
    ok('paginador: Mostrando 1 - 10 de 26, página 1 de 3', 'Mostrando 1 - 10 de 26' in pg.inner_text('#paginador') and 'Página 1 de 3' in pg.inner_text('#paginador'))
    ok('menú lateral: usuario y perfil', 'Demo Usuario' in pg.inner_text('.ev-nav__foot') and 'Administrador' in pg.inner_text('.ev-nav__foot'))
    ok('acentos correctos en el listado', 'Planificación estratégica' in pg.locator('#grid tr.ev-row').nth(0).inner_text())
    pg.screenshot(path=out + '01_listado.png', full_page=True)
    pg.select_option('#paginador select', '20'); esperar()
    ok('cambiar a 20 filas por página', filas() == 20)
    pg.fill('#txtNombreFiltro', 'gestión'); pg.click('#btnFiltrar'); esperar()
    ok('filtro por nombre: 7 filas', filas() == 7 and pg.inner_text('#tituloListado') == 'Procesos ( 7 )')
    pg.screenshot(path=out + '02_filtro.png', full_page=True)
    pg.click('#btnBorrarFiltros'); esperar()
    ok('borrar filtros: vuelve a 20 filas', filas() == 20 and pg.input_value('#txtNombreFiltro') == '')
    pg.fill('#txtCodigoFiltro', 'EJ-2'); pg.press('#txtCodigoFiltro', 'Enter'); esperar()
    ok('filtro por código con la tecla Intro: 7 filas', filas() == 7 and pg.url.endswith('Procesos.aspx'))
    pg.click('#btnBorrarFiltros'); esperar()
    pg.locator('.ev-th-btn', has_text='Nombre').click(); esperar()
    ok('ordenar por la columna Nombre', 'Activos fijos' in pg.locator('#grid tr.ev-row').nth(0).inner_text())
    pg.locator('.ev-th-btn', has_text='Nombre').click(); esperar()
    ok('segundo clic: orden descendente', 'Tesorería' in pg.locator('#grid tr.ev-row').nth(0).inner_text())
    pg.click('[aria-label="Página siguiente"]'); esperar()
    ok('página siguiente: 6 filas', filas() == 6)
    pg.click('#btnEditar'); esperar()
    ok('editar sin seleccionar fila: aviso', dlg().is_visible() and 'No se ha seleccionado ninguna fila' in dlg().inner_text())
    dlg().get_by_text('Aceptar').click()
    pg.click('#btnCrear'); pg.wait_for_selector('#txtCodigo')
    ok('alta: abre Proceso.aspx?accion=crear', 'Proceso.aspx?accion=crear' in pg.url and pg.title() == 'eVidencia: Proceso')
    ok('título de la ficha en alta', pg.inner_text('.ev-page-title') == 'Proceso (alta)')
    ok('desplegable con 14 tipos y la opción [Seleccione]', pg.locator('#ddTipoProceso option').count() == 15)
    pg.click('#btnGuardar'); pg.wait_for_selector('.ev-dialog')
    t = dlg().inner_text()
    ok('validación: tres campos obligatorios', all(x in t for x in ['El campo Código es obligatorio', 'El campo Nombre es obligatorio', 'El campo Tipo de Proceso es obligatorio']))
    pg.screenshot(path=out + '03_validacion.png')
    dlg().get_by_text('Aceptar').click()
    pg.fill('#txtCodigo', 'EJ-05'); pg.fill('#txtNombre', 'Duplicado'); pg.select_option('#ddTipoProceso', '11'); pg.click('#btnGuardar'); pg.wait_for_selector('.ev-dialog')
    ok('alta con código repetido: diálogo de error de negocio', 'Ya existe otro proceso con este mismo código' in dlg().inner_text())
    ok('tras el error se conservan los datos tecleados', pg.input_value('#txtNombre') == 'Duplicado')
    pg.screenshot(path=out + '04_codigo_repetido.png')
    dlg().get_by_text('Aceptar').click()
    pg.fill('#txtCodigo', 'DEMO-01'); pg.fill('#txtNombre', 'Proceso creado en la demo'); pg.click('#btnGuardar'); pg.wait_for_selector('#ev-toast')
    ok('alta correcta: aviso "Registro creado con éxito"', 'Registro creado con éxito' in pg.inner_text('#ev-toast'))
    ok('tras el alta la pantalla queda en edición del nuevo proceso', pg.input_value('#txtCodigo') == 'DEMO-01' and pg.input_value('input[name=hdnAccion]') == 'Editar' and pg.inner_text('.ev-page-title') == 'Proceso')
    pg.screenshot(path=out + '05_alta.png')
    pg.fill('#txtNombre', 'Proceso modificado en la demo'); pg.click('#btnGuardar'); pg.wait_for_selector('#ev-toast')
    ok('edición correcta: aviso "Registro actualizado con éxito"', 'Registro actualizado con éxito' in pg.inner_text('#ev-toast'))
    pg.click('#btnVolver'); pg.wait_for_selector('#grid tr.ev-row')
    ok('Volver regresa al listado y recupera página, filas y orden', pg.url.endswith('/Administracion/Procesos.aspx') and 'Página 2 de 2' in pg.inner_text('#paginador'))
    pg.fill('#txtCodigoFiltro', 'DEMO'); pg.click('#btnFiltrar'); esperar()
    ok('el proceso nuevo aparece en el listado con el nombre modificado', filas() == 1 and 'Proceso modificado en la demo' in pg.locator('#grid tr.ev-row').first.inner_text())
    pg.locator('#grid tr.ev-row').first.dblclick(); pg.wait_for_selector('#txtCodigo')
    ok('doble clic abre la edición con los datos', 'accion=editar' in pg.url and pg.input_value('#txtNombre') == 'Proceso modificado en la demo' and pg.input_value('#ddTipoProceso') == '11')
    pg.click('#btnVolver'); pg.wait_for_selector('#grid tr.ev-row')
    ok('al volver se recupera el filtro del listado', pg.input_value('#txtCodigoFiltro') == 'DEMO' and filas() == 1)
    pg.locator('#grid tr.ev-row [aria-label="Abrir"]').first.click(); pg.wait_for_selector('#txtCodigo')
    ok('el botón i abre la ficha', pg.input_value('#txtCodigo') == 'DEMO-01')
    pg.click('#btnVolver'); pg.wait_for_selector('#grid tr.ev-row')
    pg.locator('#grid tr.ev-row').first.click(); pg.click('#btnEliminar'); esperar()
    ok('eliminar pide confirmación con el nombre', dlg().is_visible() and 'eliminar el registro Proceso modificado en la demo' in dlg().inner_text())
    pg.screenshot(path=out + '06_confirmar_baja.png')
    dlg().get_by_text('Sí', exact=True).click(); pg.wait_for_selector('#ev-toast')
    ok('baja correcta: aviso "Registro eliminado con éxito"', 'Registro eliminado con éxito' in pg.inner_text('#ev-toast'))
    esperar()
    ok('tras la baja se mantiene el filtro y el proceso ya no aparece', pg.input_value('#txtCodigoFiltro') == 'DEMO' and filas() == 0)
    pg.click('#btnBorrarFiltros'); esperar()
    ok('sin filtros el listado vuelve a 26 registros', pg.inner_text('#tituloListado') == 'Procesos ( 26 )')
    pg.fill('#txtCodigoFiltro', 'EJ-01'); pg.click('#btnFiltrar'); esperar()
    pg.locator('#grid tr.ev-row').first.click(); pg.click('#btnEliminar'); esperar()
    dlg().get_by_text('Sí', exact=True).click(); pg.wait_for_selector('.ev-dialog')
    ok('baja de un proceso con procesos asociados: se rechaza', 'El Proceso tiene procesos asociados' in dlg().inner_text())
    pg.screenshot(path=out + '07_baja_rechazada.png')
    dlg().get_by_text('Aceptar').click(); esperar()
    ok('el proceso rechazado sigue en el listado', filas() == 1)
    r = pg.goto(B + '/Administracion/Proceso.aspx?accion=editar&IdProceso=abc')
    ok('parámetro IdProceso no válido: página de error', r.status == 500 and 'Formato del parámetro IdProceso no válido' in pg.content())
    r = pg.goto(B + '/Administracion/Proceso.aspx?accion=editar&IdProceso=9999')
    ok('proceso inexistente: página de error', r.status == 500 and 'No existe el proceso' in pg.content())
    # vista móvil
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.goto(B + '/Administracion/Procesos.aspx'); pg.wait_for_selector('#grid tr.ev-row')
    ok('móvil: el menú lateral está oculto y hay botón de menú', not pg.locator('.ev-nav').is_visible() and pg.locator('.ev-menu-btn').is_visible())
    ok('móvil: las filas se muestran como tarjetas (sin cabecera de tabla)', not pg.locator('#grid thead').is_visible())
    pg.screenshot(path=out + '08_movil.png')
    pg.click('.ev-menu-btn'); esperar()
    ok('móvil: el botón abre el menú', pg.locator('.ev-nav').is_visible())
    pg.screenshot(path=out + '09_movil_menu.png')
    b.close()
print('respuestas con error no esperadas:', [f for f in fallos if 'Proceso.aspx?accion=editar&IdProceso=' not in f])
print('errores de script:', consola)
n = sum(1 for _, c in res if c); print(f'Resultado: {n} correctas, {len(res)-n} fallidas')
